import { useRef, useState } from 'react';
import { ActivityIndicator, KeyboardAvoidingView, Platform, Pressable, ScrollView, StyleSheet, Text, TextInput, View, type ScrollViewInstance } from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import { Fanous } from '../../components/Fanous';
import { askAvailable, askQuestion, type ChatTurn } from '../../lib/ask';
import { colors } from '../../theme';

const SUGGESTIONS = [
  'What breaks wudu?',
  'How do the four madhabs differ on raising the hands in prayer?',
  'What is the reward of praying in congregation?',
  'Can I combine prayers when travelling?',
];

export default function AskScreen() {
  const [turns, setTurns] = useState<ChatTurn[]>([]);
  const [input, setInput] = useState('');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const scroll = useRef<ScrollViewInstance>(null);

  async function send(text: string) {
    const q = text.trim();
    if (!q || busy) return;
    const next: ChatTurn[] = [...turns, { role: 'user', content: q }];
    setTurns(next);
    setInput('');
    setError(null);
    setBusy(true);
    try {
      const answer = await askQuestion(next);
      setTurns([...next, { role: 'assistant', content: answer }]);
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Something went wrong.');
    } finally {
      setBusy(false);
      setTimeout(() => scroll.current?.scrollToEnd({ animated: true }), 50);
    }
  }

  return (
    <SafeAreaView style={styles.safe} edges={['top']}>
      <KeyboardAvoidingView style={{ flex: 1 }} behavior={Platform.OS === 'ios' ? 'padding' : undefined}>
        <ScrollView ref={scroll} contentContainerStyle={{ padding: 16, gap: 12, paddingBottom: 24 }}>
          <Text style={styles.title}>Ask about Islam</Text>
          <Text style={styles.note}>
            Answers cite the Quran and hadith and show where the madhabs differ. They are generated by AI and can contain
            mistakes, so check important matters with a qualified scholar.
          </Text>
          {!askAvailable && (
            <Text style={[styles.note, { color: colors.red }]}>Questions turn on once the app is connected to Supabase.</Text>
          )}

          {turns.length === 0 && (
            <View style={{ gap: 8, marginTop: 8 }}>
              <View style={{ flexDirection: 'row', alignItems: 'center', gap: 10 }}>
                <Fanous size={56} />
                <Text style={[styles.note, { flex: 1 }]}>Try one of these, or type your own question.</Text>
              </View>
              {SUGGESTIONS.map((s) => (
                <Pressable key={s} onPress={() => send(s)} style={styles.suggestion} disabled={!askAvailable}>
                  <Text style={styles.suggestionText}>{s}</Text>
                </Pressable>
              ))}
            </View>
          )}

          {turns.map((t, i) => (
            <View key={i} style={[styles.bubble, t.role === 'user' ? styles.user : styles.bot]}>
              <Text style={[styles.bubbleText, t.role === 'user' && { color: '#fff' }]}>{t.content}</Text>
            </View>
          ))}
          {busy && (
            <View style={[styles.bubble, styles.bot, { flexDirection: 'row', gap: 8, alignItems: 'center' }]}>
              <ActivityIndicator color={colors.green} />
              <Text style={styles.bubbleText}>Looking through the sources…</Text>
            </View>
          )}
          {error && <Text style={{ color: colors.red }}>{error}</Text>}
        </ScrollView>

        <View style={styles.inputRow}>
          <TextInput
            value={input}
            onChangeText={setInput}
            placeholder="Ask a question"
            placeholderTextColor={colors.muted}
            style={styles.input}
            multiline
            editable={askAvailable}
          />
          <Pressable onPress={() => send(input)} disabled={!input.trim() || busy || !askAvailable} style={[styles.send, (!input.trim() || busy) && { opacity: 0.4 }]}>
            <Text style={{ color: '#fff', fontWeight: '900', fontSize: 18 }}>↑</Text>
          </Pressable>
        </View>
      </KeyboardAvoidingView>
    </SafeAreaView>
  );
}

const styles = StyleSheet.create({
  safe: { flex: 1, backgroundColor: colors.bg },
  title: { fontSize: 26, fontWeight: '900', color: colors.ink },
  note: { color: colors.muted, lineHeight: 20 },
  suggestion: { padding: 14, borderRadius: 14, backgroundColor: colors.card, borderWidth: 2, borderColor: colors.line },
  suggestionText: { color: colors.ink, fontWeight: '600' },
  bubble: { padding: 14, borderRadius: 18, maxWidth: '90%' },
  user: { alignSelf: 'flex-end', backgroundColor: colors.green, borderBottomRightRadius: 4 },
  bot: { alignSelf: 'flex-start', backgroundColor: colors.card, borderWidth: 2, borderColor: colors.line, borderBottomLeftRadius: 4 },
  bubbleText: { fontSize: 16, lineHeight: 23, color: colors.ink },
  inputRow: { flexDirection: 'row', gap: 8, padding: 12, borderTopWidth: 2, borderTopColor: colors.line, backgroundColor: colors.bg, alignItems: 'flex-end' },
  input: { flex: 1, maxHeight: 120, padding: 12, borderRadius: 16, borderWidth: 2, borderColor: colors.line, backgroundColor: colors.card, fontSize: 16, color: colors.ink },
  send: { width: 46, height: 46, borderRadius: 23, backgroundColor: colors.green, alignItems: 'center', justifyContent: 'center' },
});

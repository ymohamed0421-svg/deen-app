// Writes supabase/seed.sql from the lesson content in src/content/units.ts.
// Run with: npm run seed
import { writeFileSync } from 'node:fs';
import { UNITS } from '../src/content/units.ts';

const q = (s: string | null | undefined) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const lines: string[] = ['-- Generated by scripts/generate-seed.ts. Do not edit by hand.', ''];

lines.push(`insert into levels (id, title, sort) values ('foundations', 'Foundations', 1) on conflict (id) do nothing;`);
UNITS.forEach((u, ui) => {
  lines.push(
    `insert into units (id, level_id, title, subtitle, color, foundation, sort) values (${q(u.id)}, 'foundations', ${q(u.title)}, ${q(u.subtitle)}, ${q(u.color)}, ${u.foundation}, ${ui + 1}) on conflict (id) do update set title = excluded.title, subtitle = excluded.subtitle;`,
  );
  u.lessons.forEach((l, li) => {
    lines.push(
      `insert into lessons (id, unit_id, title, teach, sort, review_status) values (${q(l.id)}, ${q(u.id)}, ${q(l.title)}, ${q(l.teach)}, ${li + 1}, ${q(l.reviewStatus)}) on conflict (id) do update set title = excluded.title, teach = excluded.teach;`,
    );
    lines.push(`delete from exercises where lesson_id = ${q(l.id)};`);
    l.exercises.forEach((e, ei) => {
      lines.push(
        `insert into exercises (lesson_id, type, body, sort) values (${q(l.id)}, ${q(e.type)}, ${q(JSON.stringify(e))}::jsonb, ${ei + 1});`,
      );
    });
  });
});

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), lines.join('\n') + '\n');
console.log('Wrote supabase/seed.sql');
